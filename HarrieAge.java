public class HarrieAge {
    public static void main(String[] args) {
        // Define the birth year and current year
        int birthYear = 2000;
        int currentYear = 2024;

        // Calculate the age
        int age = currentYear - birthYear;

        // Print the result
        System.out.println("Harry's age in 2024 is " + age);
    }
}
